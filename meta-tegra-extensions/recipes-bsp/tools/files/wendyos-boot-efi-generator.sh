#!/bin/sh
# Select the ESP on the running rootfs disk, never a global PARTLABEL symlink.
# Run before local-fs.target, after the initramfs has mounted the real rootfs.
set -eu

fail() {
    message="wendyos-boot-efi-generator: $*; refusing to generate EFI mount"
    printf '%s\n' "$message" >&2
    # journald is not running yet when the generator first runs during boot.
    if [ -w /dev/kmsg ]; then
        printf '<3>%s\n' "$message" > /dev/kmsg || :
    fi
    exit 1
}

output=${1:?systemd generator output directory is required}
unit=@ESPMOUNTUNIT@

# MAJ:MIN works when the root source is reported as /dev/root or a UUID alias.
# Require a directly mounted partition: guessing through overlay/device-mapper
# or choosing an unrelated disk would risk writing firmware to the wrong ESP.
root_device=$(findmnt -nr -o MAJ:MIN --target /) || fail "cannot identify the root device"
case "$root_device" in
    ''|*[!0-9:]*|:*|*:|*:*:*) fail "invalid root device number '$root_device'" ;;
    *:*) ;;
    *) fail "invalid root device number '$root_device'" ;;
esac
root_sys=$(readlink -f "/sys/dev/block/$root_device") || fail "cannot resolve root device $root_device"
[ -f "$root_sys/partition" ] || fail "root device $root_device is not a disk partition"
disk_sys=$(dirname "$root_sys")
[ -f "$disk_sys/dev" ] || fail "cannot identify the root disk"

esp=
for partition in "$disk_sys"/*; do
    [ -f "$partition/partition" ] || continue
    [ -r "$partition/uevent" ] || continue
    label=$(sed -n 's/^PARTNAME=//p' "$partition/uevent")
    case "$label" in
        esp|UEFI-ESP) ;;
        *) continue ;;
    esac
    [ -z "$esp" ] || fail "multiple EFI partitions exist on the root disk"
    device=$(sed -n 's/^DEVNAME=//p' "$partition/uevent")
    case "$device" in
        ''|*[!a-zA-Z0-9_-]*) fail "invalid ESP device name '$device'" ;;
    esac
    esp="/dev/$device"
done
[ -n "$esp" ] || fail "no EFI partition (esp or UEFI-ESP) exists on the root disk"
fstype=$(blkid -p -s TYPE -o value -- "$esp") || fail "cannot probe $esp"
[ "$fstype" = vfat ] || fail "$esp has filesystem '$fstype', expected vfat"

# A block-device What= gives the mount its normal systemd .device dependency.
# Generate nothing until every check passes: there is no static label fallback.
# Write aside and rename: systemd loads whatever a failed generator leaves.
cat > "$output/.$unit.tmp" <<EOF
# Automatically generated by wendyos-boot-efi-generator.
[Unit]
Description=EFI System Partition on the WendyOS root disk
Before=local-fs.target

[Mount]
What=$esp
Where=@ESPMOUNT@
Type=vfat
EOF
mv -f "$output/.$unit.tmp" "$output/$unit"
mkdir -p "$output/local-fs.target.wants"
ln -sf "../$unit" "$output/local-fs.target.wants/$unit"
